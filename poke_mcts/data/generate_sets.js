'use strict';
const path = require('path');
const fs = require('fs');
const { execSync } = require('child_process');
const { convertMon, toID } = require('./convert');
const SETS_PATH = require.resolve(path.join(__dirname, '..', '..', 'pokemon-showdown', 'dist', 'data', 'random-battles', 'gen9', 'sets.json'));
require(SETS_PATH);
require.cache[SETS_PATH].exports = JSON.parse(fs.readFileSync(path.join(__dirname, 'gen9_randbats_sets.json')));
const Sim = require(path.join(__dirname, '..', '..', 'pokemon-showdown', 'dist', 'sim'));

const curated = JSON.parse(fs.readFileSync(path.join(__dirname, 'belief_curated_bits.json')));
function inferBitsFor(raw) {
  const itemBit = raw.item ? curated.items[toID(raw.item)] : undefined;
  const abilBit = curated.abilities[toID(raw.ability)];
  return (itemBit !== undefined ? 1 << itemBit : 0) | (abilBit !== undefined ? 1 << abilBit : 0);
}

const N = parseInt(process.argv[2] || '100000', 10);
const SEED_BASE = 0x6e9;

const tally = new Map(); // key -> { mon, count }
for (let i = 0; i < N; i++) {
  const team = Sim.Teams.generate('gen9randombattle', { seed: [SEED_BASE, 0, (i / 0x10000) | 0, i & 0xffff] });
  for (const raw of team) {
    const m = convertMon(raw);
    m.moves = [...m.moves].sort((a, b) => a - b); // canonical slot order
    m.infer_bits = inferBitsFor(raw);
    const key = JSON.stringify([m.species_id, m.moves, m.item_id, m.ability_id, m.tera_type, m.level, m.evs, m.ivs, m.is_female]);
    const e = tally.get(key);
    if (e) e.count++; else tally.set(key, { mon: m, count: 1 });
  }
  if ((i + 1) % 10000 === 0) console.error(`${i + 1}/${N} teams, ${tally.size} distinct sets`);
}

const bySpecies = new Map();
for (const { mon, count } of tally.values()) {
  if (!bySpecies.has(mon.species_id)) bySpecies.set(mon.species_id, []);
  bySpecies.get(mon.species_id).push({ ...mon, count });
}
for (const sets of bySpecies.values()) sets.sort((a, b) => b.count - a.count);
const speciesIds = [...bySpecies.keys()].sort((a, b) => a - b);

const POOL_MASK_BITS = 256; // pool_mask = [u64; 4]
const maxSetsPerSpecies = Math.max(...[...bySpecies.values()].map((s) => s.length));
if (maxSetsPerSpecies > POOL_MASK_BITS) throw new Error(`belief pool: ${maxSetsPerSpecies} sets/species > ${POOL_MASK_BITS}; widen pool_mask`);

let showdownCommit = 'unknown';
try {
  showdownCommit = execSync('git rev-parse HEAD', { cwd: path.join(__dirname, '..', '..', 'pokemon-showdown') }).toString().trim();
} catch {}

const meta = { n_teams: N, seed_base: SEED_BASE, showdown_commit: showdownCommit, distinct_sets: tally.size, species: speciesIds.length };
fs.writeFileSync(path.join(__dirname, 'gen9_sets.json'),
  JSON.stringify({ meta, species: Object.fromEntries(speciesIds.map((id) => [id, bySpecies.get(id)])) }) + '\n');

// Emit the Rust table (checked in; cargo build stays hermetic — engine codegen.py pattern)
let rs = `// GENERATED by data/generate_sets.js — do not edit.
// n_teams=${N} seed_base=0x${SEED_BASE.toString(16)} showdown=${showdownCommit} randbats=data/gen9_randbats_sets.json

#[derive(Default)]
pub struct SetEntry {
    pub moves: [u16; 4],
    pub item_id: u16,
    pub ability_id: u16,
    pub level: u8,
    pub tera_type: u8,
    pub is_female: bool,
    pub evs: [u8; 6],
    pub ivs: [u8; 6],
    pub count: u32,
    pub infer_bits: u32,
}

pub struct SpeciesSets {
    pub species_id: u16,
    pub total_count: u32,
    pub sets: &'static [SetEntry],
}

`;
const chunks = [];
let grandTotal = 0n;
for (const id of speciesIds) {
  const sets = bySpecies.get(id);
  const total = sets.reduce((s, x) => s + x.count, 0);
  grandTotal += BigInt(total);
  const rows = sets.map((s) =>
    `    SetEntry { moves: [${s.moves}], item_id: ${s.item_id}, ability_id: ${s.ability_id}, level: ${s.level}, tera_type: ${s.tera_type}, is_female: ${s.is_female}, evs: [${s.evs}], ivs: [${s.ivs}], count: ${s.count}, infer_bits: ${s.infer_bits} },`
  ).join('\n');
  rs += `static S${id}: &[SetEntry] = &[\n${rows}\n];\n`;
  chunks.push(`    SpeciesSets { species_id: ${id}, total_count: ${total}, sets: S${id} },`);
}
rs += `\npub static GEN9_SET_POOL: &[SpeciesSets] = &[\n${chunks.join('\n')}\n];\n`;
rs += `pub static GEN9_SET_POOL_TOTAL: u64 = ${grandTotal};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'gen_sets.rs'), rs);
console.log(`wrote ${tally.size} sets across ${speciesIds.length} species (showdown ${showdownCommit.slice(0, 12)})`);
